// Helper to generate candle datasets with indicators
export function generateCandlesForAsset(asset: MarketAsset, count = 48): CandleData[] {
  const candles: CandleData[] = [];
  const basePrice = asset.price * 0.94;
  let currentPrice = basePrice;
  const now = Date.now();
  const stepMs = 15 * 60 * 1000; // 15-minute intervals

  const closes: number[] = [];

  for (let i = 0; i < count; i++) {
    const timestamp = now - (count - 1 - i) * stepMs;
    const dateObj = new Date(timestamp);
    const timeStr = dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

    // Target the actual current price on the last candle
    const progress = i / (count - 1);
    const target = basePrice + (asset.price - basePrice) * progress;
    const volatility = (asset.high24h - asset.low24h) * 0.12 || asset.price * 0.008;

    const delta = (Math.random() - 0.46) * volatility;
    const open = currentPrice;
    let close = i === count - 1 ? asset.price : Math.max(open * 0.8, open + delta + (target - open) * 0.15);
    
    // Bounds
    const high = Math.max(open, close) + Math.random() * (volatility * 0.6);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.6);
    const volume = Math.floor(Math.random() * 85000 + 15000);

    closes.push(close);

    // Calculate MA 20
    let ma20: number | undefined;
    if (closes.length >= 10) {
      const slice = closes.slice(-20);
      ma20 = slice.reduce((a, b) => a + b, 0) / slice.length;
    }

    // Calculate EMA 50
    let ema50: number | undefined;
    if (closes.length >= 10) {
      const slice = closes.slice(-30);
      ema50 = (slice.reduce((a, b) => a + b, 0) / slice.length) * 0.995;
    }

    // Bollinger Bands
    let upperBand: number | undefined;
    let lowerBand: number | undefined;
    if (ma20 !== undefined) {
      const stdDev = volatility * 1.2;
      upperBand = ma20 + stdDev;
      lowerBand = ma20 - stdDev;
    }

    candles.push({
      time: timeStr,
      timestamp,
      open: Number(open.toFixed(asset.category === 'forex' ? 4 : 2)),
      high: Number(high.toFixed(asset.category === 'forex' ? 4 : 2)),
      low: Number(low.toFixed(asset.category === 'forex' ? 4 : 2)),
      close: Number(close.toFixed(asset.category === 'forex' ? 4 : 2)),
      volume,
      ma20: ma20 ? Number(ma20.toFixed(asset.category === 'forex' ? 4 : 2)) : undefined,
      ema50: ema50 ? Number(ema50.toFixed(asset.category === 'forex' ? 4 : 2)) : undefined,
      upperBand: upperBand ? Number(upperBand.toFixed(asset.category === 'forex' ? 4 : 2)) : undefined,
      lowerBand: lowerBand ? Number(lowerBand.toFixed(asset.category === 'forex' ? 4 : 2)) : undefined,
    });

    currentPrice = close;
  }

  return candles;
}

